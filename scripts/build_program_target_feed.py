#!/usr/bin/env python3
"""Program target setting per channel and area (owner, 6 Nov 2026) -> website/data/program_target_feed.js (window.PROGRAM_TARGET).

Source: data/catalogues/program_target_nov.csv, transcribed from the sheet "ALOKASI PROGRAM NOVEMBER" (Retail outlet: AVA 50/150, KOTKAB, PROMOTOR, OUTLET PROMOTOR;
Big outlet: TEBUS MURAH | KAM, TOP PLAYER; DTU + DSF: DTU DSE, DSF). One row per channel and area: target, units (# MC / promotor / kuota / DSE), alokasi per unit.
`program` = the program flag (kro_program_outlets.csv name) whose outlets are measured; `measure` = ga | sga ... key of kro_feed (ga, sp, vsi, vso, ssi, sso), or ga_promotor (n/a).
Edit the CSV and re-run this script to change a target or the measure of a channel; no app change is needed.
"""
import csv, json, os
from collections import OrderedDict
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, 'data', 'catalogues', 'program_target_nov.csv')
BRIDGE = os.path.join(ROOT, 'data', 'catalogues', 'program_target_bridge_nov.csv')   # guideline slides: total target per area and the per-day bridge columns
OUT = os.path.join(ROOT, 'website', 'data', 'program_target_feed.js')
AREA_KEY = {'KOTA BEKASI': 'BEKASI'}      # the feeds keep BEKASI; the app shows KOTA BEKASI


def num(v):
    v = (v or '').strip()
    return float(v) if v else None


def main():
    ch = OrderedDict()
    for r in csv.DictReader(open(CSV, encoding='utf-8')):
        c = ch.setdefault(r['channel'], {'id': r['channel'], 'label': r['label'], 'group': r['group'], 'program': r['program'], 'measure': r['measure'],
                                         'rate_rp': num(r['rate_rp']), 'rule': r['rule'], 'note': r['note'], 'areas': {}})
        a = AREA_KEY.get(r['area'].strip(), r['area'].strip())
        c['areas'][a] = {'target': num(r['target']), 'units': num(r['units']), 'alokasi': num(r['alokasi'])}
    # guideline (6 Nov 2026): Retail & KRO natural = the rest = total target of the area - Retail Program (AVA + Promotor + Kab/Kota Fokus) - Wholesaler (TM | KAM + Top Player) - D2U - DSF
    bridge = list(csv.DictReader(open(BRIDGE, encoding='utf-8'))) if os.path.exists(BRIDGE) else []
    check = []
    if bridge:
        nat = {'id': 'RETAIL & KRO NATURAL', 'label': 'RETAIL & KRO NATURAL (sisanya)', 'group': 'RETAIL & KRO', 'program': '~NP', 'measure': 'ga', 'rate_rp': None,
               'rule': 'sisanya = total target area - Retail Program - Wholesaler - D2U - DSF', 'note': 'outlet di luar semua program flag (Retail dan KRO natural)', 'areas': {}}
        for b in bridge:
            a = AREA_KEY.get(b['area'].strip(), b['area'].strip())
            rest = float(b['total_target']) - sum((c['areas'].get(a) or {}).get('target') or 0 for c in ch.values())
            nat['areas'][a] = {'target': rest, 'units': None, 'alokasi': None}
            if rest < 0:
                check.append('%s: residual negatif %s' % (a, rest))
        ch[nat['id']] = nat
    for c in ch.values():
        c['total'] = sum(a['target'] or 0 for a in c['areas'].values())
        c['units'] = sum(a['units'] or 0 for a in c['areas'].values())
    # check against the per-day figures of the guideline slides (calendar days: / 30; DSF and D2U slide 2: / 25 working days)
    grp = lambda ids, a: sum((ch[i]['areas'].get(a) or {}).get('target') or 0 for i in ids if i in ch)
    for b in bridge:
        a = AREA_KEY.get(b['area'].strip(), b['area'].strip())
        exp = {'natural': grp(['RETAIL & KRO NATURAL'], a) / 30, 'program': grp(['AVA', 'PROMOTOR', 'KOTKAB'], a) / 30, 'wholesaler': grp(['TEBUS MURAH | KAM', 'TOP PLAYER'], a) / 30,
               'd2u': grp(['DTU DSE'], a) / 30, 'dsf': grp(['DSF'], a) / 30, 'harian': float(b['total_target']) / 30, 'd2u_hari25': grp(['DTU DSE'], a) / 25, 'dsf_hari25': grp(['DSF'], a) / 25}
        for k, v in exp.items():
            if abs(v - float(b[k])) > 1.01:
                check.append('%s %s: app %.1f vs guideline %s' % (a, k, v, b[k]))
    feed = {'metadata': {'generated_at': datetime.now().replace(microsecond=0).isoformat(), 'month': '2026-11', 'source': 'data/catalogues/program_target_nov.csv (sheet ALOKASI PROGRAM NOVEMBER)',
                         'contract': 'docs/assessments/program_target_setting.md', 'daily_rule': 'daily target = monthly target / days of the month (linear), cumulative target = day x daily target', 'bridge_check': check, 'workdays': 25},
            'bridge': [{k: (AREA_KEY.get(v.strip(), v.strip()) if k == 'area' else float(v)) for k, v in b.items()} for b in bridge],
            'channels': list(ch.values())}
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Auto-generated by scripts/build_program_target_feed.py. Kontrak: docs/assessments/program_target_setting.md\nvar PROGRAM_TARGET = ')
        json.dump(feed, f, ensure_ascii=False, separators=(',', ':'))
        f.write(";\nif (typeof window !== 'undefined') window.PROGRAM_TARGET = PROGRAM_TARGET;\n")
    print('program target feed:', {c['id']: c['total'] for c in ch.values()})
    print('bridge check vs guideline:', check or 'OK')


if __name__ == '__main__':
    main()
