#!/usr/bin/env python3
"""Program target setting per channel and area (owner, 6 Nov 2026) -> website/data/program_target_feed.js (window.PROGRAM_TARGET).

Source: data/catalogues/program_target_nov.csv, transcribed from the sheet "ALOKASI PROGRAM NOVEMBER" (Retail outlet: AVA 50/150, KOTKAB, PROMOTOR, OUTLET PROMOTOR;
Big outlet: TEBUS MURAH | KAM, TOP PLAYER; DTU + DSF: DTU DSE, DSF). One row per channel and area: target, units (# MC / promotor / kuota / DSE), alokasi per unit.
`program` = the program flag (kro_program_outlets.csv name) whose outlets are measured; `measure` = ga | sga ... key of kro_feed (ga, sp, vsi, vso, ssi, sso), or ga_promotor (n/a).
Edit the CSV and re-run this script to change a target or the measure of a channel; no app change is needed.
"""
import csv, json, os
from collections import OrderedDict
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, 'data', 'catalogues', 'program_target_nov.csv')
OUT = os.path.join(ROOT, 'website', 'data', 'program_target_feed.js')
AREA_KEY = {'KOTA BEKASI': 'BEKASI'}      # the feeds keep BEKASI; the app shows KOTA BEKASI


def num(v):
    v = (v or '').strip()
    return float(v) if v else None


def main():
    ch = OrderedDict()
    for r in csv.DictReader(open(CSV, encoding='utf-8')):
        c = ch.setdefault(r['channel'], {'id': r['channel'], 'label': r['label'], 'group': r['group'], 'program': r['program'], 'measure': r['measure'],
                                         'rate_rp': num(r['rate_rp']), 'rule': r['rule'], 'note': r['note'], 'areas': {}})
        a = AREA_KEY.get(r['area'].strip(), r['area'].strip())
        c['areas'][a] = {'target': num(r['target']), 'units': num(r['units']), 'alokasi': num(r['alokasi'])}
    for c in ch.values():
        c['total'] = sum(a['target'] or 0 for a in c['areas'].values())
        c['units'] = sum(a['units'] or 0 for a in c['areas'].values())
    feed = {'metadata': {'generated_at': datetime.now().replace(microsecond=0).isoformat(), 'month': '2026-11', 'source': 'data/catalogues/program_target_nov.csv (sheet ALOKASI PROGRAM NOVEMBER)',
                         'contract': 'docs/assessments/program_target_setting.md', 'daily_rule': 'daily target = monthly target / days of the month (linear), cumulative target = day x daily target'},
            'channels': list(ch.values())}
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Auto-generated by scripts/build_program_target_feed.py. Kontrak: docs/assessments/program_target_setting.md\nvar PROGRAM_TARGET = ')
        json.dump(feed, f, ensure_ascii=False, separators=(',', ':'))
        f.write(";\nif (typeof window !== 'undefined') window.PROGRAM_TARGET = PROGRAM_TARGET;\n")
    print('program target feed:', {c['id']: c['total'] for c in ch.values()})


if __name__ == '__main__':
    main()
